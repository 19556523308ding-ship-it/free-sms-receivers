const DICTS = { zh: ZH, en: EN };
const D = DICTS[LANG] || ZH;

/** 取文案；{name} 形式做变量插值。缺失时回落中文，再回落 key 本身。 */
export function t(key, vars) {
  let s = D[key];
  if (s == null) s = ZH[key];
  if (s == null) return key;
  if (vars) {
    for (const k in vars) s = s.split('{' + k + '}').join(String(vars[k]));
  }
  return s;
}

/** 给 HTML 属性用（不插值、已含标签时原样返回） */
export const tRaw = t;

/** 切换语言的 URL：保持当前页面路径，在中/英前缀之间转换 */
export function altLangUrl(target) {
  let p = location.pathname + location.search + location.hash;
  const isEn = /^\/en(\/|$)/.test(location.pathname);
  if (target === 'en' && !isEn) {
    p = '/en' + (location.pathname === '/' ? '/' : location.pathname) + location.search + location.hash;
  } else if (target === 'zh' && isEn) {
    p = location.pathname.replace(/^\/en(\/|$)/, '/') + location.search + location.hash;
  }
  return p;
}

/** 跳转到另一种语言，并记住选择 */
export function switchLang(target) {
  rememberLang(target);
  location.href = altLangUrl(target);
}

/** 国家名按语言取（数据里同时带 nameZh / nameEn） */
